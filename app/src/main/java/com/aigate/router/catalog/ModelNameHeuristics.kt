package com.aigate.router.catalog

/**
 * Разбор имён моделей и грубая оценка их веса.
 *
 * Каталоги локальных моделей (Hugging Face, теги Ollama, просто файл в папке
 * загрузок) не отдают ни числа параметров, ни кванта отдельными полями — всё
 * это зашито в имя вида `qwen3-4b-q4_K_M.gguf`. Без разбора имени невозможно
 * ни оценить размер файла до скачивания, ни решить, влезет ли модель в память
 * устройства, поэтому эвристики вынесены в одно место и покрыты тестами.
 *
 * Оценки заведомо приблизительные: точный размер известен только после
 * скачивания. Все константы подобраны так, чтобы ошибаться в сторону
 * завышения — лучше не показать модель, которая почти влезала, чем уронить
 * приложение по нехватке памяти на середине генерации.
 *
 * Файл намеренно свободен от Android-зависимостей: эвристики нужны и шлюзу,
 * и экранам каталога, и обычным JVM-тестам.
 */
object ModelNameHeuristics {

    /**
     * Бит на один вес модели для каждого известного кванта.
     *
     * Числа больше номинала («4 бита» у Q4_K_M превращаются в 4.85), потому что
     * k-кванты хранят рядом с весами масштабы блоков, а часть тензоров
     * (эмбеддинги, выходной слой) остаётся в более высокой точности. Значения
     * сверены с фактическими размерами файлов GGUF.
     */
    private val BITS_PER_WEIGHT: Map<String, Double> = mapOf(
        "Q2_K" to 3.35,
        "Q3_K_S" to 3.5,
        "Q3_K_M" to 3.9,
        "Q3_K_L" to 4.3,
        "Q4_0" to 4.55,
        "Q4_1" to 5.0,
        "Q4_K_S" to 4.6,
        "Q4_K_M" to 4.85,
        "Q5_0" to 5.55,
        "Q5_1" to 6.0,
        "Q5_K_S" to 5.55,
        "Q5_K_M" to 5.7,
        "Q6_K" to 6.6,
        "Q8_0" to 8.5,
        "IQ1_S" to 1.6,
        "IQ2_XXS" to 2.1,
        "IQ2_XS" to 2.35,
        "IQ2_S" to 2.5,
        "IQ2_M" to 2.7,
        "IQ3_XXS" to 3.05,
        "IQ3_XS" to 3.3,
        "IQ3_S" to 3.45,
        "IQ3_M" to 3.6,
        "IQ4_XS" to 4.25,
        "IQ4_NL" to 4.5,
        "F16" to 16.0,
        "BF16" to 16.0,
        "F32" to 32.0,
    )

    /**
     * Оценка для кванта, которого нет в таблице. Пять бит — примерно Q4_1:
     * новые кванты появляются регулярно, и осторожная оценка сверху лучше,
     * чем отказ работать с незнакомым именем.
     */
    private const val UNKNOWN_BITS_PER_WEIGHT = 5.0

    /**
     * Поправка на всё, что лежит в файле помимо весов: словарь, метаданные
     * GGUF, выравнивание тензоров. Десять процентов — усреднённая разница
     * между «биты × параметры» и реальным размером файла.
     */
    private const val OVERHEAD_FACTOR = 1.1

    /**
     * Кванты ищутся одним чередованием, отсортированным по убыванию длины:
     * движок регулярных выражений берёт первую подходящую ветку, а не самую
     * длинную, и без сортировки `IQ2_XXS` разобралось бы как `IQ2_XS`.
     *
     * Границы по обе стороны не дают зацепиться за середину слова: иначе
     * `bf16` прочиталось бы как `F16`, то есть 16 бит вместо 16 — совпало бы
     * случайно, а вот `Q4_K_M` внутри длинного слова совпало бы ошибочно.
     */
    private val QUANT_RE: Regex = Regex(
        BITS_PER_WEIGHT.keys
            .sortedByDescending { it.length }
            .joinToString(separator = "|", prefix = "(?<![A-Za-z0-9])(?:", postfix = ")(?![A-Za-z0-9])"),
        RegexOption.IGNORE_CASE,
    )

    /**
     * Число параметров в форме MoE: `8x7b` — восемь экспертов по семь
     * миллиардов. Проверяется раньше обычной формы, иначе из `8x7b`
     * извлеклось бы 7 вместо 56.
     */
    private val MOE_PARAMS_RE: Regex =
        Regex("""(?<![A-Za-z0-9.])(\d+)\s*[xX]\s*(\d+(?:[._]\d+)?)\s*[bB](?![A-Za-z0-9])""")

    /**
     * Обычная форма: `7b`, `0.6B`, `1_5b`, `235b`.
     *
     * Суффикс `b` обязателен и должен стоять на границе слова — только он
     * отличает число параметров от номера версии (`llama-3.2`, `gemma3`) и от
     * цифр кванта (`q4_0`). Слева цифра тоже должна начинать слово, иначе
     * `2.5` в `qwen2.5` дало бы «пять миллиардов».
     */
    private val PLAIN_PARAMS_RE: Regex =
        Regex("""(?<![A-Za-z0-9.])(\d+(?:[._]\d+)?)\s*[bB](?![A-Za-z0-9])""")

    /**
     * Квант из имени файла или тега: `qwen3-4b-q4_K_M.gguf`, `4b-q4_K_M`,
     * `:q4_0`, `Model.Q5_K_M.gguf`. Регистр входа не важен, на выходе всегда
     * каноническая запись верхним регистром.
     *
     * @return канонический квант либо null, если в имени его нет
     */
    fun parseQuant(name: String): String? = QUANT_RE.find(name)?.value?.uppercase()

    /** Бит на вес по названию кванта; незнакомый квант — осторожная оценка. */
    fun bitsPerWeight(quant: String): Double =
        BITS_PER_WEIGHT[quant.trim().uppercase()] ?: UNKNOWN_BITS_PER_WEIGHT

    /**
     * Число параметров в миллиардах из имени модели.
     *
     * Для MoE возвращается произведение (`8x7b` → 56.0): по памяти такая
     * модель стоит как все эксперты вместе, даже если на каждом токене
     * считаются не все.
     *
     * @return миллиарды параметров либо null, если в тексте их нет
     */
    fun parseParamsB(text: String): Double? {
        val moe = MOE_PARAMS_RE.find(text)
        if (moe != null) {
            val experts = toParams(moe.groupValues[1])
            val each = toParams(moe.groupValues[2])
            if (experts != null && each != null) return experts * each
        }
        return PLAIN_PARAMS_RE.find(text)?.let { toParams(it.groupValues[1]) }
    }

    /** Размер файла модели по числу параметров и кванту. */
    fun estimateFileSizeBytes(paramsB: Double, quant: String): Long =
        (paramsB * 1e9 * bitsPerWeight(quant) / 8.0 * OVERHEAD_FACTOR).toLong()

    /**
     * Обратная оценка: сколько параметров у файла такого размера. Нужна для
     * уже скачанных файлов и записей каталога, где в имени указан квант, но не
     * число параметров.
     */
    fun estimateParamsB(fileSizeBytes: Long, quant: String): Double =
        fileSizeBytes / (1e9 * bitsPerWeight(quant) / 8.0 * OVERHEAD_FACTOR)

    /** `1_5` и `0.6` — одно и то же число, разделитель зависит от каталога. */
    private fun toParams(raw: String): Double? =
        raw.replace('_', '.').toDoubleOrNull()?.takeIf { it > 0.0 }
}
